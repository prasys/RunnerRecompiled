"""Compiles the Mirror's Edge direct resolve compute shaders (me_direct_resolve_*.comp, next to
this script) with the NDK glslc, validates them with spirv-val and writes the SPIR-V words to
work/references/rexglue-sdk/include/rex/graphics/vulkan/me_direct_resolve_shaders.h.
Run from the project root, then compile_gpu_objects.py. Usage: python build_direct_resolve.py"""
import struct, subprocess, sys
from pathlib import Path

root = Path.cwd()
here = Path(__file__).resolve().parent
tools = root / 'work/toolchains/android-ndk-r30/shader-tools/windows-x86_64'
out_dir = root / 'work/gpu-port'
header = root / 'work/references/rexglue-sdk/include/rex/graphics/vulkan/me_direct_resolve_shaders.h'
lines = ['#pragma once', '// Generated by xbox/gpu-port/build_direct_resolve.py - do not edit.', '#include <cstdint>']
for source in sorted(here.glob('me_direct_resolve_*.comp')):
    spv = out_dir / (source.stem + '.spv')
    subprocess.run([str(tools / 'glslc.exe'), '-O', '--target-env=vulkan1.0', '-o', str(spv), str(source)], check=True)
    subprocess.run([str(tools / 'spirv-val.exe'), str(spv)], check=True)
    data = spv.read_bytes()
    words = struct.unpack('<' + 'I' * (len(data) // 4), data)
    lines.append(f'inline constexpr uint32_t {source.stem}_spv[] = {{' + ','.join(hex(w) for w in words) + '};')
    print(f'{source.name}: {len(words)} words')
header.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(header)
